import importlib.util
import tempfile
import unittest
from pathlib import Path

from dc.core.config import load_config
from dc.core.io import atomic_write_json
from dc.core.process import run_process
from dc.core.tools import find_tool, require_tool
from dc.ingest import ingest, ffprobe
from dc.qa import measure_audio_alignment
from dc.renderer import make_render_plan, render


@unittest.skipUnless(find_tool("ffmpeg") and find_tool("ffprobe") and importlib.util.find_spec("PIL") and importlib.util.find_spec("cv2"), "Real FFmpeg render dependencies unavailable")
class RenderAcceptanceTests(unittest.TestCase):
    def test_nonzero_trim_and_capped_moving_path_preserve_video_audio_time(self):
        from PIL import Image
        with tempfile.TemporaryDirectory(prefix="render acceptance ") as folder:
            work = Path(folder)
            source_path = work / "timestamp colors.mp4"
            graph = "color=c=red:s=320x180:r=60:d=1[r];color=c=green:s=320x180:r=60:d=1[g];color=c=blue:s=320x180:r=60:d=1[b];[r][g][b]concat=n=3:v=1:a=0[v];aevalsrc=0.2*sin(2*PI*(300*t+100*t*t)):s=48000:d=3[a]"
            run_process([require_tool("ffmpeg"), "-hide_banner", "-loglevel", "error", "-y", "-filter_complex", graph, "-map", "[v]", "-map", "[a]", "-c:v", "libx264", "-crf", "0", "-c:a", "aac", source_path], cwd=work, timeout=60)
            config = load_config(overrides={"output": {"preset": "ultrafast"}})
            source = ingest(source_path, work, rights_class="own", rights_note="Synthetic fixture generated by this test")
            candidate = {"id": "c_trim", "start": 2.0, "end": 2.8, "hook": {"headline_options": ["Color test"]}}
            plan = make_render_plan(source, candidate, config, work)
            feed = config.regions["feed"]
            self.assertEqual(plan["boundary_guards"],{"top_px":4,"bottom_px":4,"location":"inside_feed","version":1})
            from dc.renderer import _filter_script
            legacy={key:value for key,value in plan.items() if key!="boundary_guards"}
            self.assertNotIn("drawbox=x=0:y=0:w=iw:h=",_filter_script(legacy,config,work,True))
            for moving in (False, True):
                if moving:
                    height = 170.0
                    width = height * feed["w"] / feed["h"]
                    plan["framing"]["segments"][0]["mode"] = "SINGLE"
                    plan["framing"]["path"] = [{"t": 0, "x": 20.0, "y": 5.0, "w": width, "h": height}, {"t": .8, "x": 24.8, "y": 5.0, "w": width, "h": height}]
                output = work / ("moving.mp4" if moving else "static.mp4")
                render(plan, config, work, output)
                probe = ffprobe(output)
                video = next(stream for stream in probe["streams"] if stream["codec_type"] == "video")
                self.assertEqual(video["avg_frame_rate"], "30/1")
                self.assertLessEqual(abs(int(video["nb_frames"]) - 24), 2)
                self.assertAlmostEqual(float(probe["format"]["duration"]), .8, delta=.1)
                image_path = work / "frame.png"
                run_process([require_tool("ffmpeg"), "-hide_banner", "-loglevel", "error", "-y", "-i", output, "-frames:v", "1", image_path], timeout=30)
                with Image.open(image_path) as image:
                    rgb=image.convert("RGB")
                    red, green, blue = rgb.getpixel((feed["w"] // 2, feed["y"] + feed["h"] // 2))
                    self.assertGreaterEqual(min(rgb.getpixel((feed["w"]//2,feed["y"]-1))),250)
                    self.assertGreaterEqual(min(rgb.getpixel((feed["w"]//2,feed["y"]+feed["h"]+4))),250)
                self.assertGreater(blue, 180, "The 2-second trim must show blue, not the red first second")
                self.assertLess(red, 30)
                alignment = measure_audio_alignment(output, plan, work)
                self.assertLessEqual(abs(alignment["offset_ms"]), 40)
                self.assertGreater(alignment["correlation"], .8)
