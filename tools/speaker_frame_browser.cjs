     await dialog.getByText("Rendering preview…",{exact:true}).waitFor({state:"hidden"});
     await dialog.getByRole("combobox",{name:"Speaker Frame layout"}).selectOption("blended");
    await dialog.getByText("Rendering preview…",{exact:true}).waitFor({state:"hidden"});
