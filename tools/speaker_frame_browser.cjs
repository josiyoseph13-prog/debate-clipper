     const result={passed:true,browser:"native Windows Edge",checks:["opt-in only","settings hint switch","real source frame picker","Duo layout and timing controls","blended live preview","draw second box","typed labels persist on reopen","save feedback and badge","Back to Auto Reframe","no JavaScript errors"],errors};
