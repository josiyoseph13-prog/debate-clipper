"""Generate hash pins from installed distributions and the PyPI release API.

This avoids repeatedly downloading every wheel when pip-compile's resolver is
unavailable. It records the *verified core environment*, not optional models.
Install optional/legacy stacks separately with requirements.txt.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
from importlib import metadata
import json
import sys
import time
import urllib.request
from pathlib import Path


EXCLUDE={"pip","uv","pip-tools","build","setuptools","wheel","pyproject-hooks"}
WINDOWS={"pywin32-ctypes":("0.2.3","sys_platform == 'win32'"),"colorama":("0.4.6","sys_platform == 'win32'")}


def fetch(item):
    name,version,marker=item
    url=f"https://pypi.org/pypi/{name}/{version}/json"
    last=None
    for attempt in range(3):
        try:
            with urllib.request.urlopen(url,timeout=60) as response:
                release=json.loads(response.read(5_000_000))
            hashes=sorted({file["digests"]["sha256"] for file in release["urls"]})
            if not hashes:raise ValueError("Release has no artifact hashes")
            line=f"{name}=={version}"+(f" ; {marker}" if marker else "")
            return name,line+" \\\n"+" \\\n".join("    --hash=sha256:"+digest for digest in hashes)+"\n"
        except Exception as exc:
            last=exc
            time.sleep(attempt+1)
    raise RuntimeError(f"Cannot obtain authenticated release hashes for {name}: {last}")


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument("--output",type=Path,default=Path("requirements.lock"))
    parser.add_argument("--profile",default="core")
    args=parser.parse_args()
    distributions={dist.metadata["Name"].lower().replace("_","-"):dist.version for dist in metadata.distributions()}
    items=[]
    for name,version in sorted(distributions.items()):
        if name in EXCLUDE:continue
        marker="sys_platform == 'linux'" if name in {"secretstorage","jeepney"} else None
        items.append((name,version,marker))
    for name,(version,marker) in WINDOWS.items():
        if name not in distributions:items.append((name,version,marker))
    with ThreadPoolExecutor(max_workers=4) as pool:
        blocks=sorted(pool.map(fetch,items))
    header=f"# Verified {args.profile} environment lock; Python {sys.version.split()[0]}\n# Generated by tools/lock_verified_environment.py from PyPI SHA-256 metadata.\n# Scope: the actual installed profile; other optional stacks use requirements.txt.\n# Validate wheels on the intended Windows/Python version before installation.\n\n"
    temporary=args.output.with_suffix(".lock.part")
    temporary.write_text(header+"\n".join(block for _,block in blocks),encoding="utf-8")
    temporary.replace(args.output)
    print(json.dumps({"packages":len(blocks),"output":str(args.output),"python":sys.version.split()[0]}))


if __name__=="__main__":main()
